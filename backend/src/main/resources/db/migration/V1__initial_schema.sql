-- CommerceHub shop database, version 1.
-- From here on the schema is changed only by adding a new file (V2, V3, ...).
-- Flyway records which files have run, so every database ends up identical.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(255) NOT NULL CHECK (role IN ('CUSTOMER', 'ADMIN'))
);

CREATE TABLE categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(255)   NOT NULL UNIQUE,
    name        VARCHAR(255)   NOT NULL,
    description VARCHAR(1000),
    price       NUMERIC(12, 2) NOT NULL,
    stock       INTEGER        NOT NULL CHECK (stock >= 0),   -- the database itself refuses overselling
    category_id BIGINT         NOT NULL REFERENCES categories (id),
    active      BOOLEAN        NOT NULL,
    created_at  TIMESTAMP(6)   NOT NULL
);

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT  NOT NULL REFERENCES users (id),
    product_id BIGINT  NOT NULL REFERENCES products (id),
    quantity   INTEGER NOT NULL,
    UNIQUE (user_id, product_id)
);

CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number     VARCHAR(255)   NOT NULL UNIQUE,
    user_id          BIGINT         NOT NULL REFERENCES users (id),
    status           VARCHAR(255)   NOT NULL
        CHECK (status IN ('PENDING_PAYMENT', 'PLACED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    total            NUMERIC(12, 2) NOT NULL,
    shipping_address VARCHAR(500)   NOT NULL,
    created_at       TIMESTAMP(6)   NOT NULL
);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES orders (id),
    product_id   BIGINT         NOT NULL REFERENCES products (id),
    product_name VARCHAR(255)   NOT NULL,
    unit_price   NUMERIC(12, 2) NOT NULL,
    quantity     INTEGER        NOT NULL
);

CREATE TABLE payments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT       NOT NULL UNIQUE REFERENCES orders (id),
    gateway_order_id   VARCHAR(255) NOT NULL UNIQUE,
    gateway_payment_id VARCHAR(255),
    amount_paise       BIGINT       NOT NULL,
    status             VARCHAR(255) NOT NULL
        CHECK (status IN ('CREATED', 'PAID', 'EXPIRED', 'NEEDS_REFUND')),
    created_at         TIMESTAMP(6) NOT NULL,
    paid_at            TIMESTAMP(6)
);

CREATE TABLE outbox_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     VARCHAR(255)  NOT NULL UNIQUE,
    event_type   VARCHAR(255)  NOT NULL,
    order_number VARCHAR(255)  NOT NULL,
    payload      VARCHAR(2000) NOT NULL,
    created_at   TIMESTAMP(6)  NOT NULL,
    published_at TIMESTAMP(6)
);
